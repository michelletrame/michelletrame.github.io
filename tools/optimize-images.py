#!/usr/bin/env python3
"""Resize + convert source images to WebP for the site.

Usage: python3 tools/optimize-images.py SRC_DIR [OUT_DIR] [DATA_FILE]
  SRC_DIR    one sub-folder per case study (e.g. apf/, vouch/) of originals
  OUT_DIR    default assets/img
  DATA_FILE  default _data/images.yml

For each image writes OUT_DIR/<slug>/<name>-800.webp, plus <name>-1600.webp
when the original is wider than 800px (capped at 1600, never upscaled).
Existing outputs are skipped, so re-runs only process new photos.
DATA_FILE records the original size so templates can emit width/height
and the right srcset.
"""
import re, sys
from pathlib import Path
from PIL import Image, ImageOps

src = Path(sys.argv[1])
out = Path(sys.argv[2] if len(sys.argv) > 2 else 'assets/img')
data_file = Path(sys.argv[3] if len(sys.argv) > 3 else '_data/images.yml')

def slugify(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-') or 'image'

def save(im, w, path):
    if path.exists():
        return
    r = im if im.width <= w else im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
    r.save(path, 'WEBP', quality=80, method=6)

entries = {}
if data_file.exists():  # keep entries for images whose originals aren't in SRC_DIR this run
    for line in data_file.read_text().splitlines():
        m = re.match(r'"?([^":]+)"?: \[(\d+), (\d+)\]', line)
        if m:
            entries[m[1]] = (int(m[2]), int(m[3]))

for folder in sorted(p for p in src.iterdir() if p.is_dir()):
    for f in sorted(folder.iterdir()):
        if f.suffix.lower() not in {'.jpg', '.jpeg', '.png', '.webp'}:
            continue
        name = slugify(f.stem)
        dest = out / folder.name
        dest.mkdir(parents=True, exist_ok=True)
        im = ImageOps.exif_transpose(Image.open(f))
        im = im.convert('RGBA' if im.mode in ('RGBA', 'LA', 'P') else 'RGB')
        save(im, 800, dest / f'{name}-800.webp')
        if im.width > 800:
            save(im, 1600, dest / f'{name}-1600.webp')
        entries[f'{folder.name}/{name}'] = (im.width, im.height)

data_file.parent.mkdir(parents=True, exist_ok=True)
data_file.write_text('# Generated by tools/optimize-images.py: original [width, height]\n' +
                     ''.join(f'"{k}": [{w}, {h}]\n' for k, (w, h) in sorted(entries.items())))
print(f'{len(entries)} images -> {out}, sizes in {data_file}')
